function spread_for($pkgId) {
    switch ($pkgId) {
        case 'quick':  return [['คำตอบของคุณ', 'answer', '']];
        case 'three':  return [['อดีต', 'past', ''], ['ปัจจุบัน', 'present', ''], ['อนาคต', 'future', '']];
        case 'love':   return [
            ['ใจของคุณ', 'self', 'love'], ['ใจของเขา', 'other', 'love'], ['สิ่งที่ผูกพันคุณสองคน', 'bond', 'love'],
