// สุ่มไพ่ให้ลูกค้า (สุ่มฝั่งเซิร์ฟเวอร์ ลูกค้าโกงไม่ได้)
function draw_cards($n) {
    global $CARDS;
    $idx = range(0, count($CARDS) - 1);
    for ($i = count($idx) - 1; $i > 0; $i--) {
        $j = random_int(0, $i);
        [$idx[$i], $idx[$j]] = [$idx[$j], $idx[$i]];
    }
    return array_slice($idx, 0, $n);
}

// สร้างคำทำนายจากไพ่ที่ได้
function build_reading(array $order) {
    global $CARDS, $TONE_LINES, $TOPIC_NAMES;
    $spread = spread_for($order['pkg_id']);
    $userTopic = $order['topic'] ?: 'general';
    $items = [];
    $score = 0;
    foreach ($order['cards'] as $i => $ci) {
        [$label, $type, $topic] = $spread[$i];
        $topic = $topic ?: $userTopic;
        $c = $CARDS[$ci];
        $text = $TONE_LINES[$type][$c['tone'] + 1] . ' ' . $c[$topic];
        if ($type === 'month' || $type === 'advice' || $type === 'outcome') $text .= ' คำแนะนำ: ' . $c['advice'];
        $items[] = ['label' => $label, 'card' => $c, 'text' => $text];
        $score += $c['tone'];
    }
    $n = count($items);
    $avg = $n ? $score / $n : 0;
    $pct = (int)round((($avg + 1) / 2) * 70 + 25);

    $mainTopic = $order['pkg_id'] === 'love' ? 'love' : ($order['pkg_id'] === 'career' ? 'work' : $userTopic);
    $tn = $TOPIC_NAMES[$mainTopic];
    if ($avg >= 0.5)      $overall = "ภาพรวมเรื่อง{$tn}ของคุณอยู่ในช่วงขาขึ้นอย่างชัดเจน ไพ่ส่วนใหญ่ให้พลังบวก สิ่งที่ตั้งใจไว้มีแนวโน้มสำเร็จ ขอให้มั่นใจในตัวเองและเดินหน้าต่อ";
    elseif ($avg >= 0)    $overall = "ภาพรวมเรื่อง{$tn}ค่อนข้างดี มีทั้งโอกาสและบทเรียนปะปนกัน ถ้าคุณใช้สติและทำตามคำแนะนำของไพ่ ผลลัพธ์จะออกมาในทางที่ดี";
    else                  $overall = "ไพ่ชุดนี้เตือนให้ระมัดระวังเรื่อง{$tn}เป็นพิเศษ แต่ไม่ได้แปลว่าร้าย เป็นสัญญาณให้เตรียมตัว ปรับแผน และดูแลใจตัวเองให้ดี แล้วทุกอย่างจะค่อย ๆ คลี่คลาย";

    $good = array_values(array_filter($items, function ($it) { return $it['card']['tone'] > 0; }));
    $warn = array_values(array_filter($items, function ($it) { return $it['card']['tone'] < 0; }));
    $highlight = $good ? 'จุดเด่นของคุณอยู่ที่ไพ่ ' . implode(', ', array_map(function ($it) { return $it['card']['th'] . ' (' . $it['label'] . ')'; }, array_slice($good, 0, 3))) . ' ซึ่งเป็นพลังที่ช่วยผลักดันคุณ' : '';
    $caution = $warn ? 'สิ่งที่ต้องระวังคือ ' . implode(', ', array_map(function ($it) { return $it['label'] . ' ที่ได้ไพ่' . $it['card']['th']; }, $warn)) . ' ให้ใส่ใจเรื่องนี้เป็นพิเศษ' : 'ไม่มีไพ่เตือนแรง ๆ ในชุดนี้ ถือว่าเป็นสัญญาณที่ดี';

    $last = $items[$n - 1]['card'];
    $answer = '';
    if ($order['pkg_id'] === 'quick') $answer = $TONE_LINES['answer'][$last['tone'] + 1];

    // ของมงคลประจำคำทำนาย
    $sum = array_sum($order['cards']);
    $colors = ['ทอง', 'ชมพู', 'เขียว', 'ม่วง', 'ฟ้า', 'ขาว', 'แดง'];
    $days = ['อาทิตย์', 'จันทร์', 'อังคาร', 'พุธ', 'พฤหัสบดี', 'ศุกร์', 'เสาร์'];
    $lucky = ['color' => $colors[$sum % 7], 'number' => ($sum % 9) + 1, 'day' => $days[($sum + $n) % 7]];

    return compact('items', 'pct', 'overall', 'highlight', 'caution', 'answer', 'lucky') + ['advice' => $last['advice'], 'topic' => $tn];
}

// คำทำนายฟรีแบบย่อ (หน้าแรก) ตั้งใจให้สั้นกว่าแบบเสียเงิน
function build_free_reading(array $cards, $topic) {
    global $CARDS, $TOPIC_NAMES;
    $pos = ['อดีต', 'ปัจจุบัน', 'อนาคต'];
    $out = ['topic' => $topic, 'topic_name' => $TOPIC_NAMES[$topic], 'cards' => []];
    $score = 0;
    foreach ($cards as $i => $ci) {
        $c = $CARDS[$ci];
        $out['cards'][] = ['pos' => $pos[$i], 'n' => $c['n'], 'en' => $c['en'], 'th' => $c['th'], 'sym' => $c['sym'],
                           'kw' => $c['kw'], 'text' => $c[$topic]];
        $score += $c['tone'];
    }
    $tn = $TOPIC_NAMES[$topic];
    $out['pct'] = (int)round((($score + 3) / 6) * 70 + 25);
    if ($score >= 2)      $out['mood'] = "พลังงานโดยรวมสดใสมาก ดวงเรื่อง{$tn}ของคุณกำลังเป็นขาขึ้น";
    elseif ($score >= 0)  $out['mood'] = "พลังงานโดยรวมค่อนข้างดี เรื่อง{$tn}มีทั้งโอกาสและบทเรียนปนกัน";
    else                  $out['mood'] = "ไพ่ชุดนี้เตือนให้ระมัดระวังเรื่อง{$tn}เป็นพิเศษ เป็นสัญญาณให้ตั้งสติก่อนตัดสินใจ";
    return $out;
}
