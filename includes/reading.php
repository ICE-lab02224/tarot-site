            ['บทสรุปความสัมพันธ์', 'outcome', 'love']];
        case 'career': return [
            ['สถานการณ์ตอนนี้', 'present', 'work'], ['จุดแข็งของคุณ', 'strength', 'work'], ['อุปสรรค', 'obstacle', 'work'],
            ['เรื่องเงิน', 'money', 'money'], ['โอกาสที่กำลังมา', 'opportunity', 'work'], ['คำแนะนำ', 'advice', 'work'],
            ['ผลลัพธ์', 'outcome', 'work']];
        case 'year':
            $months = ['มกราคม','กุมภาพันธ์','มีนาคม','เมษายน','พฤษภาคม','มิถุนายน','กรกฎาคม','สิงหาคม','กันยายน','ตุลาคม','พฤศจิกายน','ธันวาคม'];
            $s = [['ภาพรวมทั้งปี', 'overview', 'general']];
            $m = (int)date('n'); // เริ่มจากเดือนถัดไป
            for ($i = 0; $i < 12; $i++) $s[] = [$months[($m + $i) % 12], 'month', 'general'];
            return $s;
    }
    return [];
}

